/** Fixed prefix hashed with the device key material (itdb_hash58.c). */
const FIXED = new Uint8Array([
  0x67,0x23,0xFE,0x30,0x45,0x33,0xF8,0x90,0x99,0x21,0x07,0xC1,0xD0,0x12,0xB2,0xA1,0x07,0x81,
]);

/** mhbd header offsets (see module doc). */
export const MHBD_HASH58_OFFSET = 0x58;
export const MHBD_HASHING_SCHEME_OFFSET = 0x30;
export const MHBD_DB_ID_OFFSET = 0x18;
export const MHBD_UNK32_OFFSET = 0x32;
export const MHBD_HASH58_LEN = 20;

function gcd(a: number, b: number): number {
  for (;;) { a = a % b; if (a === 0) return b; b = b % a; if (b === 0) return a; }
}

function lcm(a: number, b: number): number {
  if (a === 0 || b === 0) return 1;
  return (a * b) / gcd(a, b);
}

/**
 * Derive the 20-byte HMAC key from the FireWire GUID
 * (libgpod's `generate_key`): builds a 16-byte value `y` from the LCM
 * of each pair of GUID bytes through the two S-boxes, then
 * `key = SHA1(fixed || y)`.
 */
export function generateKey(firewireGuidBytes: Uint8Array): Uint8Array {
  const y = new Uint8Array(16);
  for (let i = 0; i < 4; i++) {
    const a = firewireGuidBytes[i * 2];
    const b = firewireGuidBytes[i * 2 + 1];
    const curLcm = lcm(a, b);
    const hi = (curLcm & 0xff00) >> 8;
    const lo = curLcm & 0xff;
    y[i * 4] = HASH58_TABLE1[hi];
    y[i * 4 + 1] = HASH58_TABLE2[hi];
    y[i * 4 + 2] = HASH58_TABLE1[lo];
    y[i * 4 + 3] = HASH58_TABLE2[lo];
  }
  const pre = new Uint8Array(FIXED.length + y.length);
  pre.set(FIXED);
  pre.set(y, FIXED.length);
  return sha1(pre);
}

/**
 * Compute the hash58 HMAC-SHA1 of the full iTunesDB bytes
 * (libgpod's `itdb_compute_hash`). The caller must zero db_id,
 * unk_0x32 and hash58 and set hashing_scheme beforehand.
 * @returns 20-byte digest.
 */
export function computeHash58(firewireGuidBytes: Uint8Array, itdb: Uint8Array): Uint8Array {
  const key = generateKey(firewireGuidBytes);
  return hmacSha1(key, itdb);
}

/**
 * Apply the hash58 checksum to a serialized iTunesDB buffer, returning a
 * patched copy. The original buffer is not modified.
 *
 * Faithful to `itdb_hash58_write_hash`: db_id and unk_0x32 are zeroed
 * (and restored after), hashing_scheme@0x30 = 1, hash58@0x58 = digest.
 *
 * @param itdb           - Byte buffer of the full iTunesDB (>= 0x6c bytes, "mhbd" magic).
 * @param firewireGuidHex - The device's FireWire GUID as hex (e.g. from SysInfo).
 * @returns A patched copy with the checksum applied.
 */
export function applyHash58(itdb: Uint8Array, firewireGuidHex: string): Uint8Array {
  if (itdb.length < 0x6c) throw new Error('iTunesDB buffer too small to write checksum');
  const magic = String.fromCharCode(itdb[0], itdb[1], itdb[2], itdb[3]);
  if (magic !== 'mhbd') throw new Error(`Expected "mhbd" magic, got "${magic}"`);

  const guid = fromHex(firewireGuidHex);
  const out = new Uint8Array(itdb);

  const dbIdBackup = out.slice(MHBD_DB_ID_OFFSET, MHBD_DB_ID_OFFSET + 8);
  const unk32Backup = out.slice(MHBD_UNK32_OFFSET, MHBD_UNK32_OFFSET + 20);

  out.fill(0, MHBD_DB_ID_OFFSET, MHBD_DB_ID_OFFSET + 8);
  out.fill(0, MHBD_UNK32_OFFSET, MHBD_UNK32_OFFSET + 20);
  out.fill(0, MHBD_HASH58_OFFSET, MHBD_HASH58_OFFSET + MHBD_HASH58_LEN);
  const dv = new DataView(out.buffer);
  dv.setUint16(MHBD_HASHING_SCHEME_OFFSET, 1, true);

  const digest = computeHash58(guid, out);
  out.set(digest, MHBD_HASH58_OFFSET);

  out.set(dbIdBackup, MHBD_DB_ID_OFFSET);
  out.set(unk32Backup, MHBD_UNK32_OFFSET);
  return out;
}
